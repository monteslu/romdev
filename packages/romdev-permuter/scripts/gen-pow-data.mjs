#!/usr/bin/env node
// Regenerate src/pow-data.js from the ARM optimized-routines pow tables as
// shipped in musl (src/math/pow_data.c, src/math/exp_data.c); glibc carries
// the same tables. Values are kept as IEEE-754 bit patterns so nothing is
// re-rounded on the way.
//   node scripts/gen-pow-data.mjs <pow_data.c> <exp_data.c>
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const [powFile, expFile] = process.argv.slice(2);
if (!expFile) { console.error("usage: node scripts/gen-pow-data.mjs <pow_data.c> <exp_data.c>"); process.exit(2); }

/** A C hex-float literal (0x1.8p52, -0x1p-1) as exact bits. */
function hexFloatBits(lit) {
  const m = /^(-?)0x([0-9a-f]+)(?:\.([0-9a-f]*))?p([+-]?\d+)$/i.exec(lit.trim());
  if (!m) throw new Error(`not a hex float: ${lit}`);
  const frac = m[3] ?? "";
  let mant = BigInt("0x" + m[2] + frac);
  let exp = Number(m[4]) - 4 * frac.length;
  if (mant === 0n) return m[1] ? 0x8000000000000000n : 0n;
  // Normalise to 53 bits (these literals are exact doubles, so no rounding).
  let bitsLen = mant.toString(2).length;
  while (bitsLen > 53) { if (mant & 1n) throw new Error(`inexact literal ${lit}`); mant >>= 1n; exp++; bitsLen--; }
  while (bitsLen < 53) { mant <<= 1n; exp--; bitsLen++; }
  const e = BigInt(exp + 52 + 1023);
  if (e <= 0n || e >= 0x7ffn) throw new Error(`out of normal range: ${lit}`);
  return (m[1] ? 1n << 63n : 0n) | (e << 52n) | (mant & ((1n << 52n) - 1n));
}
const f64 = (bits) => { const b = new DataView(new ArrayBuffer(8)); b.setBigUint64(0, bits); return b.getFloat64(0); };
const bitsOf = (d) => { const b = new DataView(new ArrayBuffer(8)); b.setFloat64(0, d); return b.getBigUint64(0); };
/** `lit` or `lit * k` with k a small integer (the scaled poly coefficients); exact. */
function value(expr) {
  const [a, b] = expr.split("*").map((s) => s.trim());
  const v = f64(hexFloatBits(a));
  return b ? v * Number(b) : v;
}
const hex = (d) => "0x" + bitsOf(d).toString(16).padStart(16, "0");

const pow = readFileSync(powFile, "utf8");
const ln2hi = value(/\.ln2hi = ([^,]+),/.exec(pow)[1]);
const ln2lo = value(/\.ln2lo = ([^,]+),/.exec(pow)[1]);
const poly = /\.poly = \{([\s\S]*?)\},/.exec(pow)[1].split("\n").map((l) => l.replace(/\/\/.*/, "").trim()).filter(Boolean)
  .map((l) => value(l.replace(/,$/, "")));
const tab = [...pow.matchAll(/^A\(([^,]+), ([^,]+), ([^)]+)\)/gm)].map((m) => [value(m[1]), value(m[2]), value(m[3])]);
if (tab.length !== 128 || poly.length !== 7) throw new Error("unexpected pow_data shape");

const exp = readFileSync(expFile, "utf8");
const N = 128;
const invln2N = value(/\.invln2N = ([^,]+) \* N,/.exec(exp)[1]) * N;
const negln2hiN = value(/\.negln2hiN = ([^,]+),/.exec(exp)[1]);
const negln2loN = value(/\.negln2loN = ([^,]+),/.exec(exp)[1]);
const shift = value(/#else\n\.shift = ([^,]+),/.exec(exp)[1]);
const epoly = /\.poly = \{([\s\S]*?)\},/.exec(exp)[1].split("\n").map((l) => l.replace(/\/\/.*/, "").trim()).filter(Boolean)
  .map((l) => value(l.replace(/,$/, "")));
const etab = /\.tab = \{([\s\S]*?)\},\s*\};/.exec(exp)[1].split(/[\s,]+/).filter((t) => /^0x/.test(t)).map((t) => BigInt(t));
if (etab.length !== 2 * N || epoly.length !== 4) throw new Error("unexpected exp_data shape");

const here = path.dirname(fileURLToPath(import.meta.url));
const out = `// Generated by scripts/gen-pow-data.mjs from the ARM optimized-routines pow
// tables (Copyright (c) 2018, Arm Limited, MIT; as shipped in musl and glibc).
// IEEE-754 bit patterns; do not edit.
const b = new DataView(new ArrayBuffer(8));
const d = (h) => { b.setBigUint64(0, BigInt(h)); return b.getFloat64(0); };

export const POW_LOG = {
  ln2hi: d("${hex(ln2hi)}"),
  ln2lo: d("${hex(ln2lo)}"),
  poly: [${poly.map((v) => `d("${hex(v)}")`).join(", ")}],
  // [invc, logc, logctail] per subinterval
  tab: [
${tab.map((r) => `    [${r.map((v) => `d("${hex(v)}")`).join(", ")}],`).join("\n")}
  ],
};

export const EXP = {
  invln2N: d("${hex(invln2N)}"),
  negln2hiN: d("${hex(negln2hiN)}"),
  negln2loN: d("${hex(negln2loN)}"),
  shift: d("${hex(shift)}"),
  poly: [${epoly.map((v) => `d("${hex(v)}")`).join(", ")}],
  tab: [
${etab.map((v, k) => (k % 2 === 0 ? "    " : "") + `0x${v.toString(16)}n,` + (k % 2 === 1 ? "\n" : " ")).join("").trimEnd()}
  ],
};
`;
writeFileSync(path.join(here, "..", "src", "pow-data.js"), out);
console.log("wrote src/pow-data.js");
