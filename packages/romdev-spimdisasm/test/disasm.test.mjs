// Synthetic (ROM-free) tests for the spimdisasm port: symbol naming, jump
// tables, string guessing with Shift-JIS, float/double text and version gates.
// Expected texts follow upstream spimdisasm semantics; the port has also been
// checked byte-for-byte against real Python spimdisasm output trees (see the
// package report), so these pin that behaviour against regressions.
import test from "node:test";
import assert from "node:assert/strict";

import { RABBITIZER_SKIP } from "./helpers/payload.mjs";

// Loading the port loads romdev-rabbitizer's WASM; without that payload every
// test here skips with the reason instead of the file failing to import.
const spim = RABBITIZER_SKIP ? null : await import("../src/index.js");
const { common, mips } = spim ?? {};

function be(words, size) {
  const b = new Uint8Array(size ?? words.length * 4);
  const dv = new DataView(b.buffer);
  words.forEach((w, i) => dv.setUint32(i * 4, w >>> 0));
  return b;
}

function freshContext(version = "1.42.4") {
  spim.configureVersion(version);
  common.GlobalConfig.GLABEL_ASM_COUNT = false;
  const ctx = new common.Context();
  ctx.changeGlobalSegmentRanges(0, 0x1000, 0x80000000, 0x80001000);
  return ctx;
}

const JTBL_TEXT = [
  0x2c810003, // sltiu at, a0, 3
  0x10200009, // beqz at, .L8000002C
  0x00047080, // sll t6, a0, 2
  0x3c018000, // lui at, %hi(jtbl)
  0x002e0821, // addu at, at, t6
  0x8c2e0100, // lw t6, %lo(jtbl)(at)
  0x01c00008, // jr t6
  0x00000000,
  0x03e00008, // case label
  0x24020001,
  0x03e00008,
  0x00001025,
];

function jumptableOutput(textWords, jtblWords) {
  const ctx = freshContext();
  const t = new mips.sections.SectionText(ctx, 0, 0x30, 0x80000000, "t", be(textWords, 0x100), 0, null);
  t.analyze();
  const r = new mips.sections.SectionRodata(ctx, 0, 0x10, 0x80000100, "r", be(jtblWords), 0, null);
  r.analyze();
  return [t.disassemble(), r.disassemble(), t, r];
}

test("jump table: hi/lo pair, jr, jlabel and .word .L entries", { skip: RABBITIZER_SKIP }, () => {
  const [text, rodata] = jumptableOutput(JTBL_TEXT, [0x80000020, 0x80000028, 0x80000020, 0]);
  assert.equal(
    text,
    `/* Generated by spimdisasm 1.42.4 */

nonmatching func_80000000, 0x30

glabel func_80000000
    /* 000000 80000000 2C810003 */  sltiu       $at, $a0, 0x3
    /* 000004 80000004 10200009 */  beqz        $at, .L8000002C
    /* 000008 80000008 00047080 */   sll        $t6, $a0, 2
    /* 00000C 8000000C 3C018000 */  lui         $at, %hi(jtbl_80000100)
    /* 000010 80000010 002E0821 */  addu        $at, $at, $t6
    /* 000014 80000014 8C2E0100 */  lw          $t6, %lo(jtbl_80000100)($at)
    /* 000018 80000018 01C00008 */  jr          $t6
    /* 00001C 8000001C 00000000 */   nop
  jlabel .L80000020
    /* 000020 80000020 03E00008 */  jr          $ra
    /* 000024 80000024 24020001 */   addiu      $v0, $zero, 0x1
  jlabel .L80000028
    /* 000028 80000028 03E00008 */  jr          $ra
  .L8000002C:
    /* 00002C 8000002C 00001025 */   move       $v0, $zero
endlabel func_80000000
`,
  );
  assert.equal(
    rodata,
    `/* Generated by spimdisasm 1.42.4 */

nonmatching jtbl_80000100

dlabel jtbl_80000100
    /* 000000 80000100 80000020 */ .word .L80000020
    /* 000004 80000104 80000028 */ .word .L80000028
    /* 000008 80000108 80000020 */ .word .L80000020
    /* 00000C 8000010C 00000000 */ .word 0x00000000
enddlabel jtbl_80000100
`,
  );
});

test("jump table output changes when one input word is perturbed", { skip: RABBITIZER_SKIP }, () => {
  const [, base] = jumptableOutput(JTBL_TEXT, [0x80000020, 0x80000028, 0x80000020, 0]);
  const [, pert] = jumptableOutput(JTBL_TEXT, [0x80000020, 0x80000024, 0x80000020, 0]);
  assert.notEqual(base, pert);
  assert.match(pert, /\.word \.L80000024/);
});

function stringRodata(bytesAt, encoding = "SHIFT-JIS") {
  const ctx = freshContext();
  const G = common.GlobalConfig;
  G.RODATA_STRING_ENCODING = encoding;
  G.RODATA_STRING_GUESSER_LEVEL = 2;
  const b = new Uint8Array(0x40);
  for (const [o, arr] of bytesAt) b.set(arr, o);
  for (const [o] of bytesAt) ctx.globalSegment.addSymbol(0x80000100 + o);
  const r = new mips.sections.SectionRodata(ctx, 0, 0x10, 0x80000100, "r", b, 0, null);
  r.analyze();
  return r.disassemble();
}

test("string guesser: Shift-JIS text, 0x5C trail byte split, escapes", { skip: RABBITIZER_SKIP }, () => {
  const out = stringRodata([
    [0x00, [0x82, 0xa0, 0x82, 0xa2, 0x41, 0x00, 0, 0]],
    [0x08, [0x83, 0x5c, 0x0a, 0x22, 0x00, 0, 0, 0]],
  ]);
  assert.equal(
    out,
    `/* Generated by spimdisasm 1.42.4 */

.align 2
nonmatching RO_STR_80000100

dlabel RO_STR_80000100
    /* 000000 80000100 */ .asciz "あいA"
    /* 82A082A241000000 */
.align 2
enddlabel RO_STR_80000100

.align 2
nonmatching RO_STR_80000108

dlabel RO_STR_80000108
    /* 000008 80000108 */ .ascii "\\x83"
                      .ascii "\\x5C"
                      .asciz "\\n\\""
    /* 835C0A2200000000 */
.align 2
enddlabel RO_STR_80000108
`,
  );
});

test("string guesser: a Shift-JIS decode error keeps the symbol as words", { skip: RABBITIZER_SKIP }, () => {
  // 0x85 0x40 is an unassigned JIS X 0208 row: CPython's shift_jis raises
  const bad = stringRodata([[0x00, [0x85, 0x40, 0x42, 0x00]], [0x08, [0x41, 0x42, 0x00, 0x00]]]);
  assert.match(bad, /dlabel RO_80000100\n {4}\/\* 000000 80000100 85404200 \*\/ \.word 0x85404200/);
  assert.match(bad, /\.asciz "AB"/);
  // One changed byte (0x85 0x40 -> 0x82 0x60, fullwidth A) flips it into a string
  const good = stringRodata([[0x00, [0x82, 0x60, 0x42, 0x00]], [0x08, [0x41, 0x42, 0x00, 0x00]]]);
  assert.match(good, /dlabel RO_STR_80000100/);
  assert.notEqual(bad, good);
  // The same bytes are not a string in ASCII
  const ascii = stringRodata([[0x00, [0x82, 0x40, 0x42, 0x00]]], "ASCII");
  assert.match(ascii, /\.word 0x82404200/);
});

test("float and double text use Python's .10g/.18g formatting", { skip: RABBITIZER_SKIP }, () => {
  const ctx = freshContext();
  const b = be([0x3f800000, 0x3dcccccd, 0x37800000, 0, 0x3fb99999, 0x9999999a, 0x7e37e43c, 0x8800759c]);
  ctx.globalSegment.addSymbol(0x80000100).setTypeSpecial("f32", false);
  ctx.globalSegment.addSymbol(0x80000110).setTypeSpecial("f64", false);
  ctx.globalSegment.addSymbol(0x80000118).setTypeSpecial("f64", false);
  const r = new mips.sections.SectionRodata(ctx, 0, 0x20, 0x80000100, "r", b, 0, null);
  r.analyze();
  const out = r.disassemble();
  assert.match(out, /3F800000 \*\/ \.float 1\n/);
  assert.match(out, /3DCCCCCD \*\/ \.float 0\.1000000015\n/);
  assert.match(out, /37800000 \*\/ \.float 1\.525878906e-05\n/);
  assert.match(out, /3FB999999999999A \*\/ \.double 0\.100000000000000006\n/);
  assert.match(out, /7E37E43C8800759C \*\/ \.double 1\.00000000000000005e\+300\n/);
  assert.match(out, /dlabel RO_FLT_80000100/);
  assert.match(out, /\.align 3\nnonmatching RO_DBL_80000110/);
});

test("ContextSymbol default names and quoting", { skip: RABBITIZER_SKIP }, () => {
  const ctx = freshContext();
  const seg = ctx.globalSegment;
  assert.equal(seg.addFunction(0x80000400).getName(), "func_80000400");
  assert.equal(seg.addBranchLabel(0x80000404).getName(), ".L80000404");
  assert.equal(seg.addJumpTable(0x80000500).getName(), "jtbl_80000500");
  const d = seg.addSymbol(0x80000600, common.FileSectionType.Rodata);
  assert.equal(d.getName(), "RO_80000600");
  d.setTypeSpecial("f32", false);
  assert.equal(d.getName(), "RO_FLT_80000600");
  const b = seg.addSymbol(0x80000700, common.FileSectionType.Bss);
  assert.equal(b.getName(), "B_80000700");
  common.GlobalConfig.AUTOGENERATED_NAMES_BASED_ON_SECTION_TYPE = false;
  assert.equal(b.getName(), "D_80000700");
  const named = seg.addSymbol(0x80000800);
  named.name = "has space";
  assert.equal(named.getName(), '"has space"');
  named.name = "a@b";
  assert.equal(named.getName(), '"a@b"');
  // 1.39 did not quote whitespace
  freshContext("1.39.3");
  const s2 = new common.Context().globalSegment.addSymbol(0x80000800);
  s2.name = "has space";
  assert.equal(s2.getName(), "has space");
});

test("version selection resets defaults and pairs rabbitizer", { skip: RABBITIZER_SKIP }, () => {
  assert.deepEqual(spim.configureVersion("1.35.0"), { spimdisasm: "1.35.0", rabbitizer: "1.13.0" });
  assert.equal(spim.__version__, "1.35.0");
  assert.equal(spim.rabbitizer.__version__, "1.13.0");
  assert.equal(common.GlobalConfig.ASM_TEXT_END_LABEL, "");
  assert.equal(common.GlobalConfig.ASM_EMIT_SIZE_DIRECTIVE, true);
  assert.equal(common.Compiler.IDO.value.prevAlign_double, null);
  assert.equal(common.Compiler.PSYQ.value.prevAlign_double, 3);

  spim.configureVersion("1.39.3");
  assert.equal(spim.rabbitizer.__version__, "1.14.3");
  assert.equal(common.GlobalConfig.ASM_NM_LABEL, "nonmatching");
  assert.equal(common.GlobalConfig.CREATE_BSS_PADS, undefined);
  assert.equal(common.Compiler.MWCCPS2.value.bigAddendWorkaroundForMigratedFunctions, true);

  spim.configureVersion("1.42.4");
  assert.deepEqual([...spim.__version_info__], [1, 42, 4]);
  assert.equal(common.GlobalConfig.CREATE_BSS_PADS, true);
  assert.equal(common.Compiler.MWCCPS2.value.bigAddendWorkaroundForMigratedFunctions, false);
  assert.throws(() => spim.configureVersion("1.40.0"));
});

test("bss pads from user-declared sizes (1.42 CREATE_BSS_PADS)", { skip: RABBITIZER_SKIP }, () => {
  const ctx = freshContext();
  const s = ctx.globalSegment.addSymbol(0x80000900);
  s.userDeclaredSize = 8;
  const bss = new mips.sections.SectionBss(ctx, 0x10, 0x10, 0x80000900, 0x80000920, "b", 0, null);
  bss.analyze();
  const out = bss.disassemble();
  assert.match(out, /dlabel B_80000900\n {4}\/\* 80000900 \*\/ \.space 0x08\n/);
  assert.match(out, /Automatically generated and unreferenced pad \*\/\ndlabel B_80000908\n {4}\/\* 80000908 \*\/ \.space 0x18\n/);
});
