#!/usr/bin/env node
// Generates src/py/cjk-tables-jp.js (decode maps used by src/py/codecs.js)
// and test/data/cjk-encmap-jp.js (encode maps, used only by the structural
// invariant tests) from CPython's Modules/cjkcodecs/mappings_jp.h.
//
// Usage: node scripts/gen-cjk-tables.mjs [path/to/mappings_jp.h] [cpythonTag]
//
// The output is deterministic: same input file -> byte-identical output.

import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { createHash } from "node:crypto";

const here = dirname(fileURLToPath(import.meta.url));
const pkgRoot = join(here, "..");

const srcPath = process.argv[2];
if (!srcPath) { console.error("usage: node scripts/gen-cjk-tables.mjs <path/to/mappings_jp.h> [cpythonTag]"); process.exit(2); }
const tag = process.argv[3] ?? "3.13";

const text = readFileSync(srcPath, "latin1");
const sha1 = createHash("sha1").update(readFileSync(srcPath)).digest("hex");

const SYM = { U: 0xfffe, N: 0xffff, M: 0xfffe, D: 0xfffd };

/** Parse `static const <type> __<name>[N] = { ... };` into a number array. */
function parseFlat(name) {
    const re = new RegExp(`static const \\w+ __${name}\\[(\\d+)\\] = \\{([^}]*)\\};`);
    const m = re.exec(text);
    if (!m) throw new Error(`array __${name} not found`);
    const declared = Number(m[1]);
    const vals = m[2].split(",").map((s) => s.trim()).filter((s) => s !== "").map((s) => {
        if (s in SYM) return SYM[s];
        const v = Number(s);
        if (!Number.isInteger(v) || v < 0 || v > 0xffff) throw new Error(`bad value ${s} in ${name}`);
        return v;
    });
    if (vals.length !== declared) throw new Error(`${name}: parsed ${vals.length} != declared ${declared}`);
    return vals;
}

/** Parse `static const struct <kind> <name>[256] = {...};` into [offset,bottom,top] or null per slot. */
function parseIndex(name) {
    const re = new RegExp(`static const struct \\w+ ${name}\\[256\\] = \\{([\\s\\S]*?)\\};`);
    const m = re.exec(text);
    if (!m) throw new Error(`index ${name} not found`);
    const body = m[1].replace(/\s+/g, "");
    const out = [];
    const entryRe = /\{([^{}]*)\}/g;
    let e;
    while ((e = entryRe.exec(body)) !== null) {
        const parts = e[1].split(",");
        if (parts.length !== 3) throw new Error(`bad entry ${e[1]} in ${name}`);
        if (parts[0] === "0") {
            out.push(null);
        } else {
            const pm = /^__(\w+)\+(\d+)$/.exec(parts[0]);
            if (!pm) throw new Error(`bad pointer ${parts[0]} in ${name}`);
            out.push([Number(pm[2]), Number(parts[1]), Number(parts[2])]);
        }
    }
    if (out.length !== 256) throw new Error(`${name}: ${out.length} entries`);
    return out;
}

function b64u16(vals) {
    const buf = Buffer.alloc(vals.length * 2);
    vals.forEach((v, i) => buf.writeUInt16LE(v, i * 2));
    return buf.toString("base64");
}

function emitTable(name) {
    const flat = parseFlat(name);
    const idx = parseIndex(name);
    // Sanity: every index slice lies inside the flat array.
    for (const ent of idx) {
        if (ent && ent[0] + (ent[2] - ent[1]) >= flat.length) throw new Error(`${name}: index out of range`);
    }
    return { name, length: flat.length, data: b64u16(flat), index: idx };
}

function fmtTable(t) {
    const idx = "[" + t.index.map((e) => (e ? `[${e.join(",")}]` : "null")).join(",") + "]";
    const lines = [];
    for (let i = 0; i < t.data.length; i += 100) lines.push(JSON.stringify(t.data.slice(i, i + 100)));
    return `export const ${t.name} = {\n    length: ${t.length},\n    index: ${idx},\n    data:\n        ${lines.join(" +\n        ")},\n};\n`;
}

const header = (what) => `// GENERATED by scripts/gen-cjk-tables.mjs - DO NOT EDIT.
// ${what}
// Source: CPython ${tag} Modules/cjkcodecs/mappings_jp.h (sha1 ${sha1}),
// itself generated by CPython's Tools/unicode/genmap_japanese.py.
// https://github.com/python/cpython/blob/${tag}/Modules/cjkcodecs/mappings_jp.h
// Copyright (c) 2001 Python Software Foundation; All Rights Reserved.
// Licensed under the Python Software Foundation License Version 2 (PSF-2.0).
//
// Format: data is a base64 little-endian Uint16 array (the C __<name> array,
// with U=0xFFFE, N=0xFFFF, D=0xFFFD); index[lead] is null or
// [offset, bottom, top] exactly like the C struct index array.
`;

const dec = ["jisx0208_decmap", "jisx0212_decmap", "cp932ext_decmap"].map(emitTable);
const enc = ["jisxcommon_encmap", "cp932ext_encmap"].map(emitTable);

mkdirSync(join(pkgRoot, "src/py"), { recursive: true });
mkdirSync(join(pkgRoot, "test/data"), { recursive: true });
writeFileSync(join(pkgRoot, "src/py/cjk-tables-jp.js"), header("Japanese decode maps (JIS X 0208, JIS X 0212, CP932 extensions).") + "\n" + dec.map(fmtTable).join("\n"));
writeFileSync(join(pkgRoot, "test/data/cjk-encmap-jp.js"), header("Japanese encode maps, used only by the structural invariant tests.") + "\n" + enc.map(fmtTable).join("\n"));
console.log(dec.concat(enc).map((t) => `${t.name}: ${t.length}`).join("\n"));
