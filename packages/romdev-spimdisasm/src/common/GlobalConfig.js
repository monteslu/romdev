export class GlobalConfigType {
  constructor() {
    Object.assign(this, defaultFields());
  }

  /** @deprecated */
  get STRING_GUESSER() {
    return this.RODATA_STRING_GUESSER_LEVEL > 0;
  }
  set STRING_GUESSER(value) {
    if (value) {
      if (this.RODATA_STRING_GUESSER_LEVEL <= 0) this.RODATA_STRING_GUESSER_LEVEL = 1;
    } else {
      this.RODATA_STRING_GUESSER_LEVEL = 0;
    }
  }

  /** @deprecated */
  get AGGRESSIVE_STRING_GUESSER() {
    return this.RODATA_STRING_GUESSER_LEVEL > 1;
  }
  set AGGRESSIVE_STRING_GUESSER(value) {
    if (value) {
      this.RODATA_STRING_GUESSER_LEVEL = 9;
    } else if (this.RODATA_STRING_GUESSER_LEVEL >= 0) {
      this.RODATA_STRING_GUESSER_LEVEL = 1;
    }
  }

  /** Reset every field to the defaults of the configured spimdisasm version. */
  resetToDefaults() {
    for (const k of Object.keys(this)) delete this[k];
    Object.assign(this, defaultFields());
  }

  /**
   * Allows changing the global configuration by setting a SPIMDISASM_SETTINGNAME
   * environment variable, e.g. SPIMDISASM_EMIT_CPLOAD=False
   */
  processEnvironmentVariables(env = typeof process !== "undefined" ? process.env : {}) {
    const attrs = new Set([...Object.keys(this), "STRING_GUESSER", "AGGRESSIVE_STRING_GUESSER"]);
    for (const attr of [...attrs].sort()) {
      const currentValue = this[attr];
      const key = `SPIMDISASM_${attr}`;
      if (!(key in env)) continue;
      let environmentValue = env[key];
      if (environmentValue === currentValue) continue;
      if (typeof currentValue === "boolean") {
        const up = environmentValue.toUpperCase();
        if (up === "TRUE") environmentValue = true;
        else if (up === "FALSE") environmentValue = false;
        else if (environmentValue === "0") environmentValue = false;
        else environmentValue = environmentValue.length > 0;
      } else if (currentValue !== null && typeof currentValue === "object" && currentValue.__enumName === "Compiler") {
        const newComp = Compiler.fromStr(environmentValue);
        if (newComp === null) {
          console.error(`Unrecognized compiler setting from environment 'SPIMDISASM_${attr.toUpperCase()}=${environmentValue}'.`);
          continue;
        }
        environmentValue = newComp;
      } else if (currentValue !== null && typeof currentValue === "object" && currentValue.__enumName === "InputEndian") {
        environmentValue = InputEndian.fromStr(environmentValue);
      } else if (currentValue !== null && typeof currentValue === "object" && currentValue.__enumName === "Abi") {
        environmentValue = Abi.fromStr(environmentValue);
      } else if (currentValue !== null && typeof currentValue === "object" && currentValue.__enumName === "ArchLevel") {
        const value = ArchLevel.fromValue(pyInt(environmentValue, 10));
        environmentValue = value !== null ? value : currentValue;
      } else if (typeof currentValue === "number") {
        environmentValue = pyInt(environmentValue, 16);
      }
      this[attr] = environmentValue;
    }
  }
}

export const GlobalConfig = new GlobalConfigType();
GlobalConfig.processEnvironmentVariables();

onVersionChange(() => {
  GlobalConfig.resetToDefaults();
  GlobalConfig.processEnvironmentVariables();
});
