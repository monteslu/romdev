export const InputEndian = createEnum(
  "InputEndian",
  [
    ["BIG", "big"],
    ["LITTLE", "little"],
    ["MIDDLE", "middle"],
  ],
  {
    toFormatString() {
      if (this === InputEndian.BIG) return ">";
      if (this === InputEndian.LITTLE) return "<";
      throw new Error(`No struct format string available for : ${this}`);
    },
  },
  {
    fromStr(value) {
      if (value === "little") return InputEndian.LITTLE;
      if (value === "middle") return InputEndian.MIDDLE;
      return InputEndian.BIG;
    },
  },
);

export const Abi = createEnum(
  "Abi",
  [
    ["O32", "O32"],
    ["N32", "N32"],
    ["O64", "O64"],
    ["N64", "N64"],
    ["EABI32", "EABI32"],
    ["EABI64", "EABI64"],
  ],
  {},
  {
    fromStr(value) {
      const m = Abi.fromValueOrNull(value);
      return m === null ? Abi.O32 : m;
    },
  },
);

