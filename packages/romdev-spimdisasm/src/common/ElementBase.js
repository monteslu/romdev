import { GlobalConfig } from "./GlobalConfig.js";
import { FileSectionType } from "./FileSectionType.js";
import { atLeast, versionString } from "../version.js";

const alwaysTrue = () => true;

export class ElementBase {
  /**
   * @param context Context
   * @param vromStart The VROM address of this element
   * @param vromEnd The end of this element's VROM address
   * @param inFileOffset The offset of this element relative to the start of its file
   * @param vram The VRAM address of this element
   * @param name The name of this element
   * @param words A list of words (4 bytes) corresponding to this element
   * @param sectionType The section type this element corresponds to
   */
  constructor(context, vromStart, vromEnd, inFileOffset, vram, name, words, sectionType, segmentVromStart, overlayCategory) {
    this.context = context;
    this.vromStart = vromStart;
    this.vromEnd = vromEnd;
    this.inFileOffset = inFileOffset;
    this.vram = vram;
    this.name = name;
    this.words = words;
    this.sectionType = sectionType;
    this.customSectionName = null;

    /** Added to the first column of the disassembled line comment */
    this.commentOffset = 0;

    /** The index of the current element inside its parent or null if unknown */
    this.index = null;

    /** For elements that are contained in other elements, like symbols inside of sections */
    this.parent = null;

    this.overlayCategory = overlayCategory ?? null;
    this.segmentVromStart = segmentVromStart;

    this._ownSegmentReference = null;
  }

  /** The amount of words this element has */
  get sizew() {
    return this.words.length;
  }

  /** The end of this element's VRAM */
  get vramEnd() {
    return this.vram + this.sizew * 4;
  }

  setVram(vram) {
    this.vram = vram;
  }

  setCommentOffset(commentOffset) {
    this.commentOffset = commentOffset;
  }

  getName() {
    return this.name;
  }

  getVromOffset(localOffset) {
    return this.vromStart + localOffset;
  }

  getVromOffsetNone(localOffset) {
    if (this.sectionType === FileSectionType.Bss) return null;
    return this.getVromOffset(localOffset);
  }

  getVramOffset(localOffset) {
    return this.vram + localOffset;
  }

  containsVram(vram) {
    if (vram < this.vram) return false;
    if (vram >= this.vramEnd) return false;
    return true;
  }

  getLabelFromSymbol(sym, symName) {
    if (sym !== null && sym !== undefined) {
      let label = sym.getLabelMacro(false);
      if (label === null) return "";
      label += ` ${symName || sym.getName()}`;
      if (sym.visibility !== null && sym.visibility !== "global") label += `, ${sym.visibility}`;
      if (GlobalConfig.GLABEL_ASM_COUNT) {
        if (this.index !== null) label += ` # ${this.index}`;
      }
      label += GlobalConfig.LINE_ENDS;
      return label;
    }
    return "";
  }

  /** Scans the words of this element, gathering as much info as possible. */
  analyze() {}

  getSpimdisasmVersionString() {
    if (!GlobalConfig.ASM_COMMENT || !GlobalConfig.ASM_GENERATED_BY) return "";
    return `/* Generated by spimdisasm ${versionString()} */${GlobalConfig.LINE_ENDS}${GlobalConfig.LINE_ENDS}`;
  }

  /** Produces a disassembly of this element. */
  disassemble(_migrate = false, _useGlobalLabel = true) {
    return "";
  }

  getSegment() {
    if (atLeast("1.42.0")) {
      if (this._ownSegmentReference !== null) return this._ownSegmentReference;

      if (this.overlayCategory !== null) {
        const segmentsPerVrom = this.context.overlaySegments.get(this.overlayCategory);
        if (segmentsPerVrom !== undefined) {
          const overlaySegment = segmentsPerVrom.get(this.segmentVromStart);
          if (overlaySegment !== undefined) {
            if (overlaySegment.isVromInRange(this.vromStart)) {
              if (this._ownSegmentReference === null) this._ownSegmentReference = overlaySegment;
              return overlaySegment;
            }
          }
        }
      }

      if (this.context.globalSegment.isVromInRange(this.vromStart)) {
        if (this._ownSegmentReference === null) this._ownSegmentReference = this.context.globalSegment;
        return this.context.globalSegment;
      }

      return this.context.unknownSegment;
    }

    // spimdisasm < 1.42
    if (this.overlayCategory !== null) {
      const segmentsPerVrom = this.context.overlaySegments.get(this.overlayCategory);
      if (segmentsPerVrom !== undefined) {
        const overlaySegment = segmentsPerVrom.get(this.segmentVromStart);
        if (overlaySegment !== undefined) {
          if (this._ownSegmentReference === null) {
            if (overlaySegment.isVromInRange(this.vromStart)) this._ownSegmentReference = overlaySegment;
          }
          return overlaySegment;
        }
      }
    }

    if (this._ownSegmentReference === null) {
      if (this.context.globalSegment.isVromInRange(this.vromStart)) this._ownSegmentReference = this.context.globalSegment;
    }
    return this.context.globalSegment;
  }

  getSegmentForVram(vram) {
    const v142 = atLeast("1.42.0");
    if (this._ownSegmentReference === null) {
      if (this.context.globalSegment.isVromInRange(this.vromStart)) this._ownSegmentReference = this.context.globalSegment;
    }
    if (this.context.globalSegment.isVramInRange(vram)) return this.context.globalSegment;

    if (v142 && this.overlayCategory === null) {
      // The owned segment is the global segment
      const prioritizedSegment = this._findPrioritizedSegment(vram, this.context.globalSegment);
      if (prioritizedSegment !== null) return prioritizedSegment;
    }

    if (this.overlayCategory !== null) {
      const segmentsPerVrom = this.context.overlaySegments.get(this.overlayCategory);
      if (segmentsPerVrom !== undefined) {
        const overlaySegment = segmentsPerVrom.get(this.segmentVromStart);
        if (overlaySegment !== undefined) {
          if (this._ownSegmentReference === null) {
            if (overlaySegment.isVromInRange(this.vromStart)) this._ownSegmentReference = overlaySegment;
          }
          if (overlaySegment.isVramInRange(vram)) return overlaySegment;

          if (v142) {
            const prioritizedSegment = this._findPrioritizedSegment(vram, overlaySegment);
            if (prioritizedSegment !== null) return prioritizedSegment;
          }
        }
      }
    }

    return this.context.unknownSegment;
  }

  getSegmentForVrom(vrom) {
    if (this._ownSegmentReference === null) {
      if (this.context.globalSegment.isVromInRange(this.vromStart)) this._ownSegmentReference = this.context.globalSegment;
    }
    if (this.context.globalSegment.isVromInRange(vrom)) return this.context.globalSegment;

    if (this.overlayCategory !== null) {
      const segmentsPerVrom = this.context.overlaySegments.get(this.overlayCategory);
      if (segmentsPerVrom !== undefined) {
        const overlaySegment = segmentsPerVrom.get(this.segmentVromStart);
        if (overlaySegment !== undefined) {
          if (this._ownSegmentReference === null) {
            if (overlaySegment.isVromInRange(this.vromStart)) this._ownSegmentReference = overlaySegment;
          }
          if (overlaySegment.isVromInRange(vrom)) return overlaySegment;
        }
      }

      // If the vrom was not part of that segment, then check for every other overlay category
      for (const [overlayCategory, segmentsPerVrom2] of this.context.overlaySegments) {
        if (this.overlayCategory !== overlayCategory) {
          for (const [segmentVrom, overlaySegment] of segmentsPerVrom2) {
            if (vrom < segmentVrom) continue;
            if (overlaySegment.isVromInRange(vrom)) return overlaySegment;
          }
        }
      }
    }

    return this.context.unknownSegment;
  }

  /**
   * Searches symbol or a symbol with an addend if `tryPlusOffset` is True.
   * Python keyword-only parameters, positional here:
   * (vramAddress, vromAddress=None, tryPlusOffset=True, checkUpperLimit=True, checkGlobalSegment=True, allowOutsideIfVramIsInside=True)
   */
  getSymbol(vramAddress, vromAddress = null, tryPlusOffset = true, checkUpperLimit = true, checkGlobalSegment = true, allowOutsideIfVramIsInside = true) {
    const v142 = atLeast("1.42.0");
    let contextSym;

    if (v142) {
      contextSym = this.context.absoluteSegment.getSymbol(vramAddress, tryPlusOffset, true);
      if (contextSym !== null) return contextSym;
    }

    if (vromAddress !== null && vromAddress !== undefined) {
      return this.getSegmentForVrom(vromAddress).getSymbol(vramAddress, tryPlusOffset, checkUpperLimit);
    }

    if (this.overlayCategory === null || checkGlobalSegment) {
      contextSym = this.context.globalSegment.getSymbol(vramAddress, tryPlusOffset, checkUpperLimit);
      if (contextSym !== null) return contextSym;

      if (v142 && this.overlayCategory === null) {
        // This is the owned segment
        contextSym = this._findInPrioritizedSegments(this.context.globalSegment, vramAddress, alwaysTrue, tryPlusOffset, checkUpperLimit);
        if (contextSym !== null) return contextSym;
      }
    }

    if (this.overlayCategory !== null) {
      const segmentsPerVrom = this.context.overlaySegments.get(this.overlayCategory);
      if (segmentsPerVrom !== undefined) {
        const overlaySegment = segmentsPerVrom.get(this.segmentVromStart);
        if (overlaySegment !== undefined) {
          if (v142) {
            let inRange = false;
            if (overlaySegment.isVramInRange(vramAddress)) {
              contextSym = overlaySegment.getSymbol(vramAddress, tryPlusOffset, checkUpperLimit);
              if (contextSym !== null) return contextSym;
              inRange = true;
            }

            contextSym = this._findInPrioritizedSegments(overlaySegment, vramAddress, alwaysTrue, tryPlusOffset, checkUpperLimit);
            if (contextSym !== null) return contextSym;

            if (inRange && !allowOutsideIfVramIsInside) return null;
          } else {
            contextSym = overlaySegment.getSymbol(vramAddress, tryPlusOffset, checkUpperLimit);
            if (contextSym !== null) return contextSym;
          }
        }
      }

      // If the vram was not part of that segment, then check for every other overlay category
      for (const [overlayCategory, segmentsPerVrom2] of this.context.overlaySegments) {
        if (this.overlayCategory !== overlayCategory) {
          for (const overlaySegment of segmentsPerVrom2.values()) {
            if (!overlaySegment.isVramInRange(vramAddress)) continue;
            contextSym = overlaySegment.getSymbol(vramAddress, tryPlusOffset, checkUpperLimit);
            if (contextSym !== null) return contextSym;
          }
        }
      }
    }

    if (!checkGlobalSegment) return null;

    if (!GlobalConfig.ALLOW_UNKSEGMENT) return null;
    contextSym = this.context.unknownSegment.getSymbol(vramAddress, tryPlusOffset, checkUpperLimit);
    if (this._ownSegmentReference !== null) {
      if (contextSym !== null && contextSym.vromAddress !== null) {
        if (!this._ownSegmentReference.isVromInRange(contextSym.getVrom())) return null;
      }
    }
    return contextSym;
  }

  /** (vramAddress, symValidation, tryPlusOffset=True, checkUpperLimit=True) */
  getSymbolFromAnySegment(vramAddress, symValidation, tryPlusOffset = true, checkUpperLimit = true) {
    const v142 = atLeast("1.42.0");
    let contextSym;
    if (v142) {
      contextSym = this.context.absoluteSegment.getSymbol(vramAddress, tryPlusOffset, true);
      if (contextSym !== null && symValidation(contextSym)) return contextSym;
    }

    contextSym = this.context.globalSegment.getSymbol(vramAddress, tryPlusOffset, checkUpperLimit);
    if (contextSym !== null && symValidation(contextSym)) return contextSym;

    if (v142 && this.overlayCategory === null) {
      contextSym = this._findInPrioritizedSegments(this.context.globalSegment, vramAddress, symValidation, tryPlusOffset, checkUpperLimit);
      if (contextSym !== null) return contextSym;
    }

    if (this.overlayCategory !== null) {
      const segmentsPerVrom = this.context.overlaySegments.get(this.overlayCategory);
      if (segmentsPerVrom !== undefined) {
        const overlaySegment = segmentsPerVrom.get(this.segmentVromStart);
        if (overlaySegment !== undefined) {
          contextSym = overlaySegment.getSymbol(vramAddress, tryPlusOffset, checkUpperLimit);
          if (contextSym !== null && symValidation(contextSym)) return contextSym;

          if (v142) {
            contextSym = this._findInPrioritizedSegments(overlaySegment, vramAddress, symValidation, tryPlusOffset, checkUpperLimit);
            if (contextSym !== null) return contextSym;
          }
        }
      }

      for (const [overlayCategory, segmentsPerVrom2] of this.context.overlaySegments) {
        if (this.overlayCategory !== overlayCategory) {
          for (const overlaySegment of segmentsPerVrom2.values()) {
            if (!overlaySegment.isVramInRange(vramAddress)) continue;
            contextSym = overlaySegment.getSymbol(vramAddress, tryPlusOffset, checkUpperLimit);
            if (contextSym !== null && symValidation(contextSym)) return contextSym;
          }
        }
      }
    }

    if (!GlobalConfig.ALLOW_UNKSEGMENT) return null;
    contextSym = this.context.unknownSegment.getSymbol(vramAddress, tryPlusOffset, checkUpperLimit);
    if (this._ownSegmentReference !== null) {
      if (contextSym !== null && contextSym.vromAddress !== null) {
        if (!this._ownSegmentReference.isVromInRange(contextSym.getVrom())) return null;
      }
    }
    if (contextSym !== null && symValidation(contextSym)) return contextSym;
    return null;
  }

  _findInPrioritizedSegments(overlaySegment, vramAddress, symValidation, tryPlusOffset, checkUpperLimit) {
    for (const prioritizedOverlay of overlaySegment.getPrioritizedSegments()) {
      for (const segmentsPerVrom of this.context.overlaySegments.values()) {
        for (const otherOverlaySegment of segmentsPerVrom.values()) {
          if (otherOverlaySegment.name === prioritizedOverlay && otherOverlaySegment.isVramInRange(vramAddress)) {
            const contextSym = otherOverlaySegment.getSymbol(vramAddress, tryPlusOffset, checkUpperLimit);
            if (contextSym !== null && symValidation(contextSym)) return contextSym;
          }
        }
      }
    }
    return null;
  }

  _findPrioritizedSegment(vram, ownedSegment) {
    for (const prioritizedSegmentName of ownedSegment.prioritizedSegments) {
      for (const segmentsPerRom of this.context.overlaySegments.values()) {
        for (const segment of segmentsPerRom.values()) {
          if (segment.name === prioritizedSegmentName && segment.isVramInRange(vram)) return segment;
        }
      }
    }
    return null;
  }

  /** (vromAddress, tryPlusOffset=True, checkUpperLimit=True) */
  getSymbolByVrom(vromAddress, tryPlusOffset = true, checkUpperLimit = true) {
    const segment = this.getSegmentForVrom(vromAddress);
    const vram = segment.vromToVram(vromAddress);
    if (vram === null) return null;
    return segment.getSymbol(vram, tryPlusOffset, checkUpperLimit);
  }

  getSymbolsRange(addressStart, addressEnd) {
    const segment = this.getSegmentForVram(addressStart);
    return segment.getSymbolsRange(addressStart, addressEnd);
  }

  getConstant(constantValue) {
    const segment = this.getSegment();
    return segment.getConstant(constantValue);
  }

  _segmentFor(vramAddress, symbolVrom) {
    if (symbolVrom !== null && symbolVrom !== undefined) return this.getSegmentForVrom(symbolVrom);
    return this.getSegmentForVram(vramAddress);
  }

  /** (vramAddress, sectionType=Unknown, isAutogenerated=False, symbolVrom=None, allowAddendInstead=False) */
  addSymbol(vramAddress, sectionType = FileSectionType.Unknown, isAutogenerated = false, symbolVrom = null, allowAddendInstead = false) {
    const segment = this._segmentFor(vramAddress, symbolVrom);
    return segment.addSymbol(vramAddress, sectionType, isAutogenerated, symbolVrom ?? null, allowAddendInstead);
  }

  /** (vramAddress, isAutogenerated=False, symbolVrom=None) */
  addFunction(vramAddress, isAutogenerated = false, symbolVrom = null) {
    return this._segmentFor(vramAddress, symbolVrom).addFunction(vramAddress, isAutogenerated, symbolVrom ?? null);
  }

  addBranchLabel(vramAddress, isAutogenerated = false, symbolVrom = null) {
    return this._segmentFor(vramAddress, symbolVrom).addBranchLabel(vramAddress, isAutogenerated, symbolVrom ?? null);
  }

  addJumpTable(vramAddress, isAutogenerated = false, symbolVrom = null) {
    return this._segmentFor(vramAddress, symbolVrom).addJumpTable(vramAddress, isAutogenerated, symbolVrom ?? null);
  }

  addJumpTableLabel(vramAddress, isAutogenerated = false, symbolVrom = null) {
    return this._segmentFor(vramAddress, symbolVrom).addJumpTableLabel(vramAddress, isAutogenerated, symbolVrom ?? null);
  }

  addGccExceptTable(vramAddress, isAutogenerated = false, symbolVrom = null) {
    return this._segmentFor(vramAddress, symbolVrom).addGccExceptTable(vramAddress, isAutogenerated, symbolVrom ?? null);
  }

  addGccExceptTableLabel(vramAddress, isAutogenerated = false, symbolVrom = null) {
    return this._segmentFor(vramAddress, symbolVrom).addGccExceptTableLabel(vramAddress, isAutogenerated, symbolVrom ?? null);
  }

  /** (vramAddress, symbolVrom=None) */
  removeSymbol(vramAddress, symbolVrom = null) {
    return this._segmentFor(vramAddress, symbolVrom).removeSymbol(vramAddress);
  }

  /** (constantValue, name, isAutogenerated=False) */
  addConstant(constantValue, name, isAutogenerated = false) {
    const segment = this.getSegment();
    return segment.addConstant(constantValue, name, isAutogenerated);
  }

  addPointerInDataReference(pointer) {
    const segment = this.getSegmentForVram(pointer);
    segment.addPointerInDataReference(pointer);
  }

  popPointerInDataReference(pointer) {
    const segment = this.getSegmentForVram(pointer);
    return segment.popPointerInDataReference(pointer);
  }

  getAndPopPointerInDataReferencesRange(low, high) {
    const segment = this.getSegmentForVram(low);
    return segment.getAndPopPointerInDataReferencesRange(low, high);
  }

  getSectionName() {
    if (this.customSectionName !== null) return this.customSectionName;
    return this.sectionType.toSectionName();
  }
}
