// splat.disassembler.disassembler_instance + spimdisasm_disassembler
import { atLeast } from '../runtime.js';
import * as log from '../util/log.js';
import { opts } from '../util/options.js';
import { spim, rabbitizer } from './spim.js';

class NullDisassembler {
  configure() {}
  check_version() {}
  known_types() { return new Set(); }
}

function versionTuple(v) { return String(v).split('.').map((x) => parseInt(x, 10)); }
function tupleLt(a, b) {
  for (let i = 0; i < Math.max(a.length, b.length); i++) {
    const x = a[i] || 0; const y = b[i] || 0;
    if (x !== y) return x < y;
  }
  return false;
}

class SpimdisasmDisassembler {
  get SPIMDISASM_MIN() { return atLeast('0.35.0') ? [1, 39, 0] : [1, 33, 0]; }

  configure() {
    const S = spim();
    const R = rabbitizer();
    const G = S.common.GlobalConfig;
    const modern = atLeast('0.35.0');

    G.PRODUCE_SYMBOLS_PLUS_OFFSET = true;
    G.TRUST_USER_FUNCTIONS = true;
    G.TRUST_JAL_FUNCTIONS = true;
    G.GLABEL_ASM_COUNT = false;
    G.ASM_COMMENT_OFFSET_WIDTH = opts.rom_address_padding ? 6 : 0;
    G.AUTOGENERATED_NAMES_BASED_ON_SECTION_TYPE = false;
    G.AUTOGENERATED_NAMES_BASED_ON_DATA_TYPE = false;
    G.SYMBOL_FINDER_FILTERED_ADDRESSES_AS_HILO = false;
    if (opts.rodata_string_guesser_level !== null) G.RODATA_STRING_GUESSER_LEVEL = opts.rodata_string_guesser_level;
    if (opts.data_string_guesser_level !== null) G.DATA_STRING_GUESSER_LEVEL = opts.data_string_guesser_level;

    R.config.regNames_userFpcCsr = false;
    R.config.regNames_vr4300Cop0NamedRegisters = false;
    R.config.misc_opcodeLJust = opts.mnemonic_ljust - 1;
    R.config.regNames_gprAbiNames = R.Abi.fromStr(opts.mips_abi_gpr);
    R.config.regNames_fprAbiNames = R.Abi.fromStr(opts.mips_abi_float_regs);

    G.ENDIAN = opts.endianness === 'big' ? S.common.InputEndian.BIG : S.common.InputEndian.LITTLE;

    R.config.pseudos_pseudoMove = false;

    const selected = opts.compiler;
    const spimCompiler = S.common.Compiler.fromStr(selected.name);
    if (spimCompiler === null || spimCompiler === undefined) {
      log.write(`Unsupported selected compiler for spimdisasm: ${selected.name}`, { status: 'error' });
      log.error(`The following options are supported: [${Object.keys(S.common.compilerOptions).map((k) => `'${k}'`).join(', ')}]`);
    }
    G.COMPILER = spimCompiler;
    if (selected.name === 'SN64') {
      R.config.regNames_namedRegisters = false;
      R.config.toolchainTweaks_sn64DivFix = true;
      G.ASM_COMMENT = false;
      G.SYMBOL_FINDER_FILTERED_ADDRESSES_AS_HILO = false;
    }
    if (modern && opts.align_on_branch_labels) G.ASM_EMIT_ALIGN_BRANCH_LABELS = true;
    R.config.toolchainTweaks_treatJAsUnconditionalBranch = selected.j_as_branch;

    G.DETECT_REDUNDANT_FUNCTION_END = opts.detect_redundant_function_end;
    G.GP_VALUE = opts.gp;

    G.ASM_TEXT_LABEL = opts.asm_function_macro;
    G.ASM_TEXT_ALT_LABEL = opts.asm_function_alt_macro;
    G.ASM_JTBL_LABEL = opts.asm_jtbl_label_macro;
    G.ASM_DATA_LABEL = opts.asm_data_macro;
    G.ASM_TEXT_END_LABEL = opts.asm_end_label;
    if (modern) G.ASM_DATA_END_LABEL = opts.asm_data_end_label;
    G.ASM_EHTBL_LABEL = opts.asm_ehtable_label_macro;
    if (modern) G.ASM_NM_LABEL = opts.asm_nonmatching_label_macro;

    if (opts.asm_emit_size_directive !== null) G.ASM_EMIT_SIZE_DIRECTIVE = opts.asm_emit_size_directive;

    if (G.ASM_TEXT_LABEL === '.globl') {
      G.ASM_TEXT_ENT_LABEL = '.ent';
      G.ASM_TEXT_FUNC_AS_LABEL = true;
    }
    if (G.ASM_DATA_LABEL === '.globl') G.ASM_DATA_SYM_AS_LABEL = true;

    G.LINE_ENDS = opts.c_newline;
    G.ALLOW_ALL_ADDENDS_ON_DATA = opts.allow_data_addends;
    G.DISASSEMBLE_UNKNOWN_INSTRUCTIONS = opts.disasm_unknown;
  }

  check_version(skipVersionCheck, splatVersion) {
    const S = spim();
    const have = S.__version_info__ ? [...S.__version_info__] : versionTuple(S.__version__);
    if (!skipVersionCheck && tupleLt(have, this.SPIMDISASM_MIN)) {
      log.error(`splat ${splatVersion} requires as minimum spimdisasm (${this.SPIMDISASM_MIN.join(', ')}), but the installed version is (${have.join(', ')})`);
    }
    log.write(`splat ${splatVersion} (powered by spimdisasm ${S.__version__})`);
  }

  known_types() {
    const t = spim().common.gKnownTypes;
    return t instanceof Set ? t : new Set(t);
  }
}

let instance = new NullDisassembler();
let initialized = false;

export function reset() { instance = new NullDisassembler(); initialized = false; }

export function createDisassemblerInstance(skipVersionCheck, splatVersion) {
  if (['n64', 'psx', 'ps2', 'psp'].includes(opts.platform)) {
    instance = new SpimdisasmDisassembler();
    initialized = true;
    instance.check_version(skipVersionCheck, splatVersion);
    instance.configure();
    return;
  }
  throw new Error('No disassembler for requested platform');
}

export function getInstance() {
  if (!initialized) throw new Error('Disassembler instance not initialized');
  return instance;
}
