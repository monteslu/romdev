#define T_DITHER 9

/* Tile indices for each char in our message — 'S' 'M' 'S' ' ' 'M' 'U'
 * 'S' 'I' 'C' ' ' 'D' 'E' 'M' 'O'. 14 cells total. */
static const uint8_t message[14] = {
  1, 2, 1, 0,    /* "SMS " */
  2, 3, 1, 4, 5, /* "MUSIC" */
  0,             /* " " */
  6, 7, 2, 8,    /* "DEMO" */
};

static void clear_name_table(void) {
  uint8_t row;
  uint8_t col;
  /* Fill with the dithered BG tile (not blank) so the whole screen reads
   * as a two-tone field and never as a blank backdrop. */
  for (row = 0; row < 28; row++) {
    for (col = 0; col < 32; col++) {
      sms_set_tilemap_cell(row, col, T_DITHER, 0);
    }
  }
}

static void draw_message(void) {
  uint8_t i;
  uint8_t row = 11;
  uint8_t col = 9;     /* (32 - 14) / 2 = 9 → roughly centered */
  for (i = 0; i < 14; i++) {
    sms_set_tilemap_cell(row, (uint8_t)(col + i), message[i], 0);
  }
}

void main(void) {
  sms_vdp_init();
  sms_load_palette(palette);
  /* BG tiles at VRAM $0000 (R4 = 0xFF, set by sms_vdp_init). */
  sms_load_tiles(0x0000, font_tiles, (uint16_t)sizeof(font_tiles));

  clear_name_table();
  draw_message();

  music_init();
  music_play(0);

  sms_vdp_display_on();

  do {
    sms_vblank_wait();
    music_update();
  } while (1);
}
