/* ── music_demo.c — SMS continuous 3-voice music demo ────────────────
 *
 * Plays a hand-authored 3-voice C-major loop forever via sms_music.{h,c}.
 * Voice 0 carries the melody on PSG channel 0, voice 1 the harmony on
 * channel 1, voice 2 the bass on channel 2. Noise channel 3 is left
 * silent so a game built on top of this can still call sfx_noise for
 * one-shot hits without colliding with the music driver.
 *
 * Display: writes the text "SMS MUSIC DEMO" centered on the BG plane
 * using a tiny hand-authored 8×8 font (only the letters we need —
 * SMUICDEO + space — so we burn a single tile per glyph and reference
 * them by name-table index).
 *
 * Build via createProject({platform:"sms", template:"music_demo"}) or
 * build({ output: "rom", platform:"sms", language:"c", sources:{ "main.c": ...,
 * "sms_music.c": ... , ...runtime... }}).
 */

