// Genesis -> sync32 native backend: a Mega Drive cartridge becomes one .s32
// (Cortex-M33 C, built by romdev's WASM arm-none-eabi toolchain).
//
// The machine around the CPU is genesis_plus_gx's own C (runtime/gpgx/, the
// pinned upstream files with ROMDEV_S32 guards: 68000 memory map, VDP with
// DMA/FIFO/HV counter, Z80, YM2612, PSG, blip_buf), cut to a Mega Drive
// cartridge and fitted to sync32 (runtime/s32/: canvas + palette output, the
// 48 kHz audio ring, the SNES-class pad, a freestanding libc). The 68000 is
// recompiled: every basic block the game was seen to execute becomes a C
// function built from gpgx's own Musashi handler, partially evaluated for that
// opcode at that address (ctrans-c.js over ../../wat/genesis/gpgx-derived);
// Musashi itself stays linked as the fallback interpreter for everything else.
//
// Timing profiles (options.profile):
//   'exact' (default): cycles charged per instruction and blocks stop at
//     every m68k_run boundary, which keeps the 68000 instruction-for-
//     instruction with gpgx (and so the whole machine state, every frame).
//   'fast': cycles charged once per block (flushed before any access that can
//     observe the clock), interrupts and line ends at block ends. Measured on
//     a 512 KB platformer: ~3% cheaper per frame than 'exact', but the moved
//     interrupt points change the game's own timeline within seconds.
//
// LICENSE: contains Genesis Plus GX code (non-commercial, see NOTICE).
//
// Plain JS ESM + JSDoc.

import { createHash } from "node:crypto";
import { readFileSync, readdirSync } from "node:fs";
import { createRequire } from "node:module";
import { tablesSource } from "./tables.js";
import { cartLicence } from "../../licence.js";
import { loadGpgxData } from "../../wat/genesis/gpgx-data.js";
import { normalizeRom, cartMapper, sramConfig, eepromConfig, sixButtonPads, cartHardware, palTiming } from "../../wat/genesis/index.js";

export const platforms = ["genesis", "md", "megadrive"];
export const REFERENCE_CORE = "genesis_plus_gx";
const RUNTIME = new URL("./runtime/", import.meta.url);

/** Defines every runtime translation unit is compiled with. */
// ALT_RENDERER is gpgx's own alternative Mode 5 background path (planes merged
// while plane B is drawn, one pass fewer); same pixels, measured 17% faster on
// sync32.
export const RUNTIME_DEFINES = ["-DLSB_FIRST", "-DALIGN_LONG", "-DROMDEV_S32", "-DUSE_16BPP_RENDERING", "-DALT_RENDERER"];
/** Hot inner loops that -O3 measured faster on s32core (sound chips, renderer, Z80). */
export const O3_UNITS = ["ym2612.c", "vdp_render.c", "z80.c", "blip_buf.c", "psg.c"];
/** Warnings gpgx's own sources raise under these flags (not errors). */
const QUIET = ["-Wno-unused-variable", "-Wno-unused-but-set-variable", "-Wno-unused-function", "-Wno-discarded-qualifiers",
  "-Wno-missing-braces", "-Wno-return-type", "-Wno-maybe-uninitialized", "-Wno-pointer-sign", "-Wno-parentheses"];
export const RUNTIME_CFLAGS = [...RUNTIME_DEFINES, "-fno-tree-loop-distribute-patterns", ...QUIET];

/** gpgx files this runtime does not compile (replaced by runtime/s32). */
const SKIP = new Set(["system.c"]);

/** The runtime's own sources: {name: text} for .c and .h. */
export function runtimeFiles() {
  const out = {};
  for (const dir of ["gpgx", "s32"]) {
    const d = new URL(dir + "/", RUNTIME);
    for (const f of readdirSync(d)) {
      if (!/\.[ch]$/.test(f) || SKIP.has(f)) continue;
      if (out[f] != null) throw new Error(`genesis native runtime: ${f} exists in two runtime directories`);
      out[f] = readFileSync(new URL(f, d), "utf8");
    }
  }
  return out;
}

/**
 * The cartridge image as gpgx leaves cart.rom after load_rom + md_cart_init:
 * normalised (byte-swapped dumps and .smd fixed), padded with $FF to a power of
 * two of at least 64 KB, then byte-swapped to 16-bit host order.
 * @param {Uint8Array} raw
 */
export function cartImage(raw) {
  const img = normalizeRom(raw);
  let size = 0x10000;
  while (size < img.length) size <<= 1;
  const rom = new Uint8Array(size).fill(0xff);
  rom.set(img);
  for (let i = 0; i < rom.length; i += 2) { const t = rom[i]; rom[i] = rom[i + 1]; rom[i + 1] = t; }
  return { image: rom, romBytes: img.length, normalized: img };
}

/** rd_rom.c: the image as a const word array (flash). */
function romSource({ image, romBytes }) {
  const w = new Uint32Array(image.buffer, image.byteOffset, image.byteLength >> 2);
  const lines = [];
  for (let i = 0; i < w.length; i += 16) lines.push(Array.from(w.subarray(i, i + 16), (x) => "0x" + x.toString(16)).join(","));
  return `/* Generated by romdev: the cartridge ROM as gpgx's cart.rom holds it (padded to ${image.length} bytes, 16-bit host order). */\n`
    + `const unsigned int rd_rom_size = ${romBytes};\n`
    + `const unsigned int rd_rom_words[${w.length}] __attribute__((aligned(4))) = {\n${lines.join(",\n")}\n};\n`;
}

const cString = (s) => JSON.stringify(s).replace(/\?\?/g, "?\\?");

/**
 * Musashi's opcode -> handler table, halved: 16-bit handler numbers
 * (rd_m68k_jt.c, flash) and the handler list (rd_m68k_handlers.h, included
 * at the end of m68kops.h where the handlers are in scope). Both come from
 * the same m68ki_instruction_jump_table.h the gpgx-derived data was parsed
 * from, so opcode N reaches the same handler.
 */
function jumpTableFiles() {
  const D = loadGpgxData();
  const { handlers, jumpTable } = D.m68k;
  if (jumpTable.length !== 0x10000 || handlers.length > 0xffff) throw new Error("gpgx-derived: unexpected 68000 jump table shape");
  const lines = [];
  for (let i = 0; i < jumpTable.length; i += 32) lines.push(Array.from(jumpTable.slice(i, i + 32)).join(","));
  const cyc = D.m68k.tables.m68ki_cycles;
  if (cyc.length !== 0x10000) throw new Error("gpgx-derived: unexpected m68ki_cycles length");
  const clines = [];
  for (let i = 0; i < cyc.length; i += 32) clines.push(Array.from(cyc.slice(i, i + 32)).join(","));
  return {
    // m68ki_cycles.h as gpgx ships it (static const, included by m68kcpu.c)
    "m68ki_cycles.h": `/* Generated by romdev from gpgx-derived.json.gz: Musashi's base cycle table (derived from Genesis Plus GX). */\n`
      + `static const unsigned char m68ki_cycles[0x10000] =\n{\n${clines.join(",\n")}\n};\n`,
    "rd_m68k_handlers.h": `/* Generated by romdev: Musashi's handlers in jump-table order (derived from Genesis Plus GX). */\n`
      + `extern const unsigned short rd_m68k_jt[0x10000];\n`
      + `static void (*const rd_m68k_handlers[${handlers.length}])(void) = {\n  ${handlers.join(",\n  ")}\n};\n`,
    "rd_m68k_jt.c": `/* Generated by romdev: opcode -> Musashi handler number (derived from Genesis Plus GX). */\n`
      + `const unsigned short rd_m68k_jt[0x10000] = {\n${lines.join(",\n")}\n};\n`,
  };
}

/**
 * Why this backend cannot build a ROM, or null. Only a plain cartridge (with
 * or without mapped backup RAM) is modelled; everything gpgx handles with
 * extra chips is refused by name rather than built wrong.
 * @param {Uint8Array} img normalised ROM
 */
export function unsupportedReason(img) {
  const mapper = cartMapper(img);
  if (mapper.kind === null) return `genesis_plus_gx runs this cart with ${mapper.reason}, which the sync32 runtime does not model`;
  if (mapper.kind !== "default" || img.length > 0x400000) return `mapper '${mapper.kind}'${img.length > 0x400000 ? " (ROM over 4MB)" : ""} is not in the sync32 runtime yet (plain cartridges only)`;
  const eep = eepromConfig(img);
  if (eep && eep.eeprom) return "serial EEPROM cartridges are not in the sync32 runtime yet";
  if (cartHardware(img)) return "cartridge hardware (protection/extra registers) is not in the sync32 runtime yet";
  if (palTiming(img)) return "PAL cartridges are not in the sync32 runtime yet (sync32 presents at 60 Hz)";
  const txt = String.fromCharCode(...img.subarray(0x1c8, 0x1ca));
  if (txt === "SV") return "SVP cartridges are refused";
  return null;
}

/**
 * Header-derived description of the build.
 * @param {Uint8Array} raw
 * @param {object} [opts]
 */
export function describe(raw, opts = {}) {
  const bytes = raw instanceof Uint8Array ? raw : new Uint8Array(raw);
  const img = normalizeRom(bytes);
  const reason = unsupportedReason(img);
  const txt = (a, b) => Array.from(img.subarray(a, b), (c) => (c >= 0x20 && c < 0x7f ? String.fromCharCode(c) : " ")).join("").replace(/\s+/g, " ").trim();
  return {
    platform: "genesis",
    target: "sync32",
    referenceCore: REFERENCE_CORE,
    supported: reason == null,
    unsupportedReason: reason,
    romSha1: createHash("sha1").update(bytes).digest("hex"),
    romBytes: img.length,
    title: txt(0x150, 0x180) || txt(0x120, 0x150),
    sram: sramConfig(img),
    sixButton: sixButtonPads(img),
    profile: opts.profile ?? "exact",
    licenseNote: "the .s32 contains Genesis Plus GX code (runtime and 68000 handlers): non-commercial",
  };
}

/** The metadata the cart carries (rd_meta.c), read back by frame({op:'verifyRecompile'}). */
function metaJson(d, extra = {}) {
  return {
    format: "romdev-s32-recompile",
    version: 1,
    platform: "genesis",
    reference: "genesis",
    referenceCore: REFERENCE_CORE,
    romSha1: d.romSha1,
    profile: d.profile,
    warmupFrames: 0,
    // s32core and genesis_plus_gx both settle 5 frames in loadMedia and the
    // cart presents exactly once per Genesis frame, so frame F is frame F
    conventions: { settleFrames: { cart: 5, reference: 5 }, cartFrameOffset: 0 },
    license: d.licenseNote,
    licence: cartLicence("sync32-genesis"),
    ...extra,
  };
}

/**
 * Emit the C project: {files: {name: text}, cflags, meta, stats}.
 * @param {Uint8Array} raw ROM bytes
 * @param {{profile?:'fast'|'exact', blocks?:object}} [opts]
 */
export async function emitProject(raw, opts = {}) {
  const bytes = raw instanceof Uint8Array ? raw : new Uint8Array(raw);
  const d = describe(bytes, opts);
  if (!d.supported) throw new Error(`genesis -> sync32: ${d.unsupportedReason}`);
  const files = runtimeFiles();
  const cart = cartImage(bytes);
  files["rd_rom.c"] = romSource(cart);
  const t = tablesSource();
  files["rd_tables.c"] = t.source;
  Object.assign(files, jumpTableFiles());
  let blockStats = null;
  if (opts.blocks) {
    const { emitBlocks } = await import("./blocks.js");
    const b = await emitBlocks(cart, { ...opts.blocks, profile: d.profile });
    Object.assign(files, b.files);
    blockStats = b.stats;
  } else {
    files["rd_blocks.c"] = "/* no compiled blocks: every 68000 instruction runs in Musashi */\n#include \"rd_blocks.h\"\nconst rd_block_entry_t rd_block_table[1] = { { 0xffffffffu, 0 } };\nconst unsigned int rd_block_count = 0;\n";
  }
  // the Z80 driver: recompiled from the Z80 RAM image the coverage run left
  // (z80blocks.js); without one every Z80 instruction runs in gpgx's core
  let z80Stats = null;
  if (opts.z80Image) {
    const { emitZ80Blocks } = await import("./z80blocks.js");
    const z = emitZ80Blocks(opts.z80Image);
    files["rd_z80_blocks.h"] = z.source;
    z80Stats = z.stats;
  }
  const audioQuality = opts.audioQuality ?? "fast";
  if (!["fast", "hq", "half"].includes(audioQuality)) throw new Error(`genesis native: options.audioQuality must be 'hq', 'fast' or 'half', got '${audioQuality}'`);
  // audioRate 'console' (default): 48 kHz at 60 presents a second, what the
  // console ring drains. 'reference': the gpgx libretro reference's own
  // stream (audio_init(44100, 0)), a TEST build whose audio verifyRecompile
  // compares sample for sample; on hardware it would underfeed the ring.
  const audioRate = opts.audioRate ?? "console";
  if (!["console", "reference"].includes(audioRate)) throw new Error(`genesis native: options.audioRate must be 'console' or 'reference', got '${audioRate}'`);
  const meta = metaJson(d, { audioQuality, audioRate, z80: z80Stats ?? { entries: 0 }, blocks: blockStats ? { compiledPcs: blockStats.compiledPcs, blocks: blockStats.blocks } : { blocks: 0 } });
  files["rd_meta.c"] = `/* Generated by romdev: build metadata the tools read back from the image. */\nconst char rd_meta_json[] __attribute__((aligned(4))) = ${cString(JSON.stringify(meta))};\n`;
  const cflags = [...RUNTIME_CFLAGS, ...(d.profile === "fast" ? ["-DRD_PROFILE_FAST"] : []), ...(audioQuality !== "hq" ? ["-DRD_AUDIO_FAST"] : []), ...(audioQuality === "half" ? ["-DRD_FM_HALF"] : []),
    ...(audioRate === "reference" ? ["-DRD_AUDIO_RATE=44100", "-DRD_AUDIO_FPS=0"] : []), ...(z80Stats ? ["-DRD_Z80_BLOCKS"] : [])];
  return { files, cflags, meta, describe: d, blockStats, z80Stats, tableBytes: t.bytes, romImageBytes: cart.image.length };
}

