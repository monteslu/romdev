let _libgcc;
function bundledLibgcc() {
  if (_libgcc !== undefined) return _libgcc;
  try {
    const { sdk } = createRequire(import.meta.url)("romdev-platform-sync32");
    _libgcc = new Uint8Array(readFileSync(sdk.libgcc));
  } catch { _libgcc = null; }
  return _libgcc;
}

/** Sizes of the output sections, from the linker map. */
export function mapSummary(map) {
  const sym = (n) => { const m = new RegExp(`0x([0-9a-f]{8})\\s+${n} = \\.`).exec(map) || new RegExp(`0x([0-9a-f]{8})\\s+${n}\\b`).exec(map); return m ? parseInt(m[1], 16) : null; };
  const bssStart = sym("__bss_start__"), bssEnd = sym("__bss_end__"), dataStart = sym("__data_start__"), dataEnd = sym("__data_end__");
  return {
    ramBytes: bssEnd != null && dataStart != null ? bssEnd - dataStart : null,
    dataBytes: dataEnd != null && dataStart != null ? dataEnd - dataStart : null,
    bssBytes: bssEnd != null && bssStart != null ? bssEnd - bssStart : null,
  };
}

/** Per-object text+rodata bytes in the flash image (from the map). */
export function mapObjectSizes(map) {
  const out = {};
  const re = /^ \.(?:text|rodata)[^\s]*\s*(?:\n\s+)?0x([0-9a-f]{8})\s+0x([0-9a-f]+)\s+\/work\/(\S+)\.o/gm;
  let m;
  while ((m = re.exec(map))) {
    const addr = parseInt(m[1], 16);
    if (addr < 0x10000000 || addr >= 0x20000000) continue;
    out[m[3]] = (out[m[3]] ?? 0) + parseInt(m[2], 16);
  }
  return out;
}

/**
 * Compile + link + pack. Translation units compile in parallel on romdev's
 * WASM worker pool (the same cc1/as/ld/objcopy build({platform:'sync32'})
 * runs, with its flags), then one link with --gc-sections against the SDK's
 * crt0 and xip.ld.
 * @param {{files:Record<string,string>, cflags:string[]}} project
 * @param {{title?:string, id?:string, optimize?:string, perFileFlags?:Record<string,string[]>, onProgress?:(s:string)=>void}} [o]
 */
export async function buildProject(project, o = {}) {
  const { runCc1m33, runM33As, runM33Ld, runM33Objcopy } = await import("../../../../toolchains/sync32/sync32.js");
  const { packS32 } = await import("../../../../toolchains/sync32/s32-format.js");
  const { loadSdk } = await import("romdev-platform-sync32");
  const sdk = loadSdk("xip");
  const headers = { ...sdk.includes };
  for (const [n, t] of Object.entries(project.files)) if (n.endsWith(".h")) headers[n] = t;
  const base = ["-O2", "-ffunction-sections", "-fdata-sections", "-fsingle-precision-constant", "-ffreestanding"];
  const units = Object.entries(project.files).filter(([n]) => n.endsWith(".c"));
  const t0 = Date.now();
  const objects = {};
  const c0 = await runM33As({ source: sdk.crt0, includes: headers });
  if (c0.exitCode !== 0 || !c0.object) return { ok: false, stage: "as", log: c0.log };
  objects["crt0.o"] = c0.object;
  const timings = {};
  let failed = null;
  await Promise.all(units.map(async ([name, text]) => {
    const t1 = Date.now();
    const flags = [...base, ...project.cflags, ...(O3_UNITS.includes(name) ? ["-O3"] : []), ...(o.perFileFlags?.[name] ?? [])];
    const cc = await runCc1m33({ source: text, headers, options: flags });
    if (cc.exitCode !== 0 || !cc.asmSource) { failed ??= { stage: "cc1", unit: name, log: cc.log }; return; }
    const as = await runM33As({ source: cc.asmSource, includes: headers });
    if (as.exitCode !== 0 || !as.object) { failed ??= { stage: "as", unit: name, log: as.log }; return; }
    objects[name.replace(/\.c$/, ".o")] = as.object;
    timings[name] = Date.now() - t1;
    o.onProgress?.(`compiled ${name} (${((Date.now() - t1) / 1000).toFixed(1)}s)`);
  }));
  if (failed) {
    const errs = failed.log.split("\n").filter((l) => /error/.test(l)).slice(0, 30).join("\n");
    return { ok: false, stage: failed.stage, unit: failed.unit, errors: errs, log: failed.log.slice(-20000) };
  }
  const libgcc = bundledLibgcc();
  // objects in a fixed order: crt0 first, then by name, so builds reproduce
  const ordered = { "crt0.o": objects["crt0.o"] };
  for (const k of Object.keys(objects).filter((k) => k !== "crt0.o").sort()) ordered[k] = objects[k];
  const ld = await runM33Ld({ objects: ordered, linkScript: sdk.linkScript, archives: libgcc ? { "libgcc.a": libgcc } : {}, options: ["--gc-sections", ...(libgcc ? ["/work/libgcc.a"] : [])] });
  if (ld.exitCode !== 0 || !ld.elf) return { ok: false, stage: "ld", log: ld.log.slice(-20000), errors: ld.log.split("\n").filter((l) => /undefined|multiple|overflow|error/.test(l)).slice(0, 40).join("\n") };
  const oc = await runM33Objcopy({ elf: ld.elf });
  if (oc.exitCode !== 0 || !oc.binary) return { ok: false, stage: "objcopy", log: oc.log };
  const packed = packS32({ image: oc.binary, elf: ld.elf, mode: "xip", title: o.title ?? "md native", id: o.id ?? "mdnative", video: "240", api: 1 });
  const map = ld.map ?? "";
  return {
    ok: true,
    s32: packed.bytes,
    elf: ld.elf,
    map,
    imageBytes: oc.binary.length,
    ...mapSummary(map),
    buildSeconds: Math.round((Date.now() - t0) / 100) / 10,
    unitSeconds: Object.fromEntries(Object.entries(timings).sort((a, b) => b[1] - a[1]).slice(0, 8).map(([k, v]) => [k, Math.round(v / 100) / 10])),
  };
}

