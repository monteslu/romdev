// instrument-uopt.js - profiled instrumentation for statically recompiled
// IDO 5.3 uopt. The generated C file is not a stable API: function labels and
// emulated-memory addresses are tied to the input executable and the
// static-recompiler revision. This module therefore supports one pinned
// profile and refuses unknown source by default instead of pretending the
// patch is portable across IDO releases.
//
// Plain JS ESM + JSDoc.

import { createHash } from "node:crypto";
import { ValueError, strRepr } from "./py.js";
import { COLOR_REGISTERS } from "./globalcolor.js";

export const MARKER = "DKWB_UOPT_GLOBALCOLOR_V1";
export const IDO_53_V12_SHA256 = "b0058f1559441c1a194d649271eb43b8637ec255682cfdd629031340b915b13f";

const FORCE_ENTRY_RE = /^(?<phase>p[12]):w(?<web>\d+)=(?:c(?<color>\d+)|s)$/;

/** The instrumented pass copies each entry into a fixed buffer; both validators share the limit. */
export const MAX_FORCE_ENTRY = 63;

export const UNQUALIFIED_FORCE_MESSAGE = "is not a phase-qualified force control; write p1:w9=c30 for the "
  + "phase-one (callee-saved) sweep or p2:w9=c30 for the phase-two "
  + "(caller-saved) sweep, or p1:w9=s to force the split path. Entries are "
  + "comma-separated with no spaces, and p1 and p2 are disjoint web spaces: "
  + "the same web number is a different web in each phase";

/** One phase-qualified globalcolor force control. */
export class ForceEntry {
  constructor({ phase, web, color = null }) { Object.assign(this, { phase, web, color }); Object.freeze(this); }
  toString() { return `${this.phase}:w${this.web}=${this.color === null ? "s" : `c${this.color}`}`; }
}

/** Parse a CDX_FORCE string, rejecting unqualified web keys. */
export function parseForceSpecification(value) {
  if (!value) throw new ValueError("CDX_FORCE is empty; write p1:w9=c30 or p2:w9=c30");
  const entries = [];
  for (const entry of value.split(",")) {
    // re.match with a trailing $ also accepts one final newline.
    const m = FORCE_ENTRY_RE.exec(entry.endsWith("\n") ? entry.slice(0, -1) : entry);
    if (!m || entry.length > MAX_FORCE_ENTRY) throw new ValueError(`CDX_FORCE entry ${strRepr(entry)} ${UNQUALIFIED_FORCE_MESSAGE}`);
    const color = m.groups.color;
    entries.push(new ForceEntry({ phase: m.groups.phase, web: parseInt(m.groups.web, 10), color: color === undefined ? null : parseInt(color, 10) }));
  }
  return entries;
}

/** Render the color decode table as C, from the one shared integer mapping. */
export function colorRegisterTable() {
  const table = COLOR_REGISTERS;
  const colors = [...table.keys()];
  const highest = Math.max(...colors);
  const values = [];
  for (let color = 0; color <= highest; color++) values.push(table.has(color) ? `"${table.get(color)}"` : "0");
  return `#define DKWB_CDX_MAX_COLOR ${highest}\n`
    + `#define DKWB_CDX_MAX_FORCE_ENTRY ${MAX_FORCE_ENTRY}\n`
    + `static const char *dkwb_cdx_colors[DKWB_CDX_MAX_COLOR + 1] = {${values.join(", ")}};\n`;
}

