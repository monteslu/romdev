#!/usr/bin/env node
// build-sysroot.mjs - lay out the emscripten sysroot the wasm-emcc driver
// compiles and links against, without Python.
//
//   node build-sysroot.mjs headers          system/ headers -> sysroot/include
//                                           (system_libs.py install_system_headers)
//   node build-sysroot.mjs seed-libs <dir>  copy prebuilt system libraries from
//                                           an existing emscripten cache
//                                           (migration aid only: the libs were
//                                           built by embuilder; see PLAN)
//
// Paths come from emcc.mjs locate() (ROMDEV_EMSCRIPTEN_ROOT / _SYSROOT).

import fs from "node:fs";
import path from "node:path";
import { locate } from "./emcc.mjs";

const { emRoot, sysroot, emVersion } = locate();

function copyTree(src, dst, excludes = new Set()) {
  fs.mkdirSync(dst, { recursive: true });
  for (const e of fs.readdirSync(src, { withFileTypes: true })) {
    if (excludes.has(e.name)) continue;
    const s = path.join(src, e.name), d = path.join(dst, e.name);
    if (e.isDirectory()) copyTree(s, d, excludes);
    else fs.copyFileSync(s, d);
  }
}

function installHeaders() {
  const inc = path.join(sysroot, "include");
  const dirs = {
    "system/include": "", "system/lib/compiler-rt/include": "", "system/lib/libunwind/include": "",
    "system/lib/libc/musl/arch/generic": "", "system/lib/libc/musl/arch/emscripten": "", "system/lib/libc/musl/include": "",
    "system/lib/libcxx/include": "c++/v1", "system/lib/libcxxabi/include": "c++/v1", "system/lib/mimalloc/include": "",
  };
  for (const [src, dest] of Object.entries(dirs)) copyTree(path.join(emRoot, src), path.join(inc, dest), new Set(["alltypes.h.in"]));
  copyTree(path.join(emRoot, "system/lib/pkgconfig"), path.join(sysroot, "lib/pkgconfig"));
  copyTree(path.join(emRoot, "system/bin"), path.join(sysroot, "bin"));
  const [maj, min, tiny] = emVersion.split(".");
  fs.writeFileSync(path.join(inc, "emscripten/version.h"), `/* Automatically generated by tools/system_libs.py */\n#define __EMSCRIPTEN_major__ ${maj}\n#define __EMSCRIPTEN_minor__ ${min}\n#define __EMSCRIPTEN_tiny__ ${tiny}\n`);
  console.log(`headers installed into ${inc}`);
}

function seedLibs(cacheDir) {
  const src = path.join(cacheDir, "sysroot/lib/wasm32-emscripten");
  const dst = path.join(sysroot, "lib/wasm32-emscripten");
  fs.mkdirSync(dst, { recursive: true });
  let n = 0;
  for (const f of fs.readdirSync(src)) if (/\.(a|o)$/.test(f)) { fs.copyFileSync(path.join(src, f), path.join(dst, f)); n++; }
  // ports install headers into the sysroot too (zlib)
  for (const h of ["zlib.h", "zconf.h"]) {
    const p = path.join(cacheDir, "sysroot/include", h);
    if (fs.existsSync(p)) fs.copyFileSync(p, path.join(sysroot, "include", h));
  }
  console.log(`seeded ${n} prebuilt libraries from ${src}`);
}

const [cmd, arg] = process.argv.slice(2);
if (cmd === "headers") installHeaders();
else if (cmd === "seed-libs") seedLibs(arg);
else { console.error("usage: build-sysroot.mjs headers | seed-libs <emscripten-cache-dir>"); process.exit(2); }
