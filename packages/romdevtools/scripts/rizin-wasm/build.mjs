#!/usr/bin/env node
// build.mjs - build rizin -> WASM by driving emcc directly (no meson, no Python).
//
// rizin's own build is meson, a Python program, and rizin's meson.build also
// runs Python scripts at configure and build time. romdev's build is JS + WASM
// only, so this driver replaces both: plan.json holds every compile / archive /
// link step for the `rizin` binary with its exact flags (frozen from a
// configured build of the pinned commit, see extract-plan.mjs), configured/
// holds the configure-time headers, and the two build-time generators the
// binary needs are done here in JS (cmd_descs.[ch] ship in the rizin tree;
// libzip's zip_err_str.c is ported below).
//
//   node build.mjs subprojects <rizin-dir>
//       Fetch the meson wrap subprojects the plan compiles (git revision or
//       sha256-verified tarball, exactly as the .wrap files in the pinned rizin
//       tree say) and overlay subprojects/packagefiles/<patch_directory>.
//   node build.mjs build <rizin-dir> [build-dir-name]
//       Fresh build into <rizin-dir>/<build-dir-name> (default build-wasm);
//       output binrz/rizin/rizin.{js,wasm} inside it.
//
// ROMDEV_JOBS overrides compile parallelism.
import { spawn, execFileSync } from "node:child_process";
import { createHash } from "node:crypto";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const HERE = path.dirname(fileURLToPath(import.meta.url));
const PLAN = JSON.parse(fs.readFileSync(path.join(HERE, "plan.json"), "utf8"));

/** Parse a meson .wrap file (INI) into { section, keys }. */
export function parseWrap(text) {
  const out = { section: null, keys: {} };
  let cur = null;
  for (const raw of text.split("\n")) {
    const line = raw.trim();
    if (!line || line.startsWith("#") || line.startsWith(";")) continue;
    const sec = /^\[(.+)\]$/.exec(line);
    if (sec) { cur = sec[1]; if (!out.section) out.section = cur; continue; }
    if (cur !== out.section) continue;
    const eq = line.indexOf("=");
    if (eq > 0) out.keys[line.slice(0, eq).trim()] = line.slice(eq + 1).trim();
  }
  return out;
}

/**
 * libzip's create_zip_err_str.py, ported. Every `#define ZIP_ER*` line in
 * zip.h and `#define ZIP_ER_DETAIL*` line in zipint.h carries a comment
 * `/* <kind> <text> *\/`; the table entry is {kind, "<first word of text>"}.
 */
export function zipErrStr(zipH, zipintH) {
  const comment = (x) => x.slice(x.indexOf("/* ") + 3, x.indexOf("*/"));
  const entry = (x) => { const c = comment(x).split(" "); return `{${c[0]}, "${c[1]}"},`; };
  const strs = zipH.split("\n").filter((l) => l.startsWith("#define ZIP_ER")).map(entry).join("\n");
  const details = zipintH.split("\n").filter((l) => l.startsWith("#define ZIP_ER_DETAIL")).map(entry).join("\n");
  return `/*
  This file was auto-generated by Meson from zip.h and zipint.h
*/

#include "zipint.h"

#define L ZIP_ET_LIBZIP
#define N ZIP_ET_NONE
#define S ZIP_ET_SYS
#define Z ZIP_ET_ZLIB

#define E ZIP_DETAIL_ET_ENTRY
#define G ZIP_DETAIL_ET_GLOBAL

const struct _zip_err_info _zip_err_str[] = {
${strs}
};

const int _zip_err_str_count = sizeof(_zip_err_str)/sizeof(_zip_err_str[0]);

const struct _zip_err_info _zip_err_details[] = {
${details}
};

const int _zip_err_details_count = sizeof(_zip_err_details)/sizeof(_zip_err_details[0]);
`;
}

function run(cmd, args, opts = {}) {
  execFileSync(cmd, args, { stdio: "inherit", ...opts });
}

/** Subproject directory names the plan compiles from (../subprojects/<name>/...). */
function neededSubprojects() {
  const names = new Set();
  for (const c of PLAN.compile) {
    const m = /^\.\.\/subprojects\/([^/]+)\//.exec(c.src);
    if (m) names.add(m[1]);
  }
  return [...names].sort();
}

function copyTree(src, dst) {
  fs.cpSync(src, dst, { recursive: true, force: true });
}

function fetchSubprojects(rizinDir) {
  const sub = path.join(rizinDir, "subprojects");
  const wraps = new Map();
  for (const f of fs.readdirSync(sub).filter((f) => f.endsWith(".wrap"))) {
    const w = parseWrap(fs.readFileSync(path.join(sub, f), "utf8"));
    wraps.set(w.keys.directory || f.replace(/\.wrap$/, ""), w);
  }
  for (const name of neededSubprojects()) {
    const dir = path.join(sub, name);
    const w = wraps.get(name);
    if (!w) {
      if (!fs.existsSync(dir)) throw new Error(`subproject ${name} is neither in the rizin tree nor a .wrap`);
      continue; // in-tree subproject
    }
    if (fs.existsSync(dir)) { console.log(`  subproject ${name}: present`); continue; }
    if (w.section === "wrap-git") {
      const rev = w.keys.revision;
      console.log(`  subproject ${name}: git ${w.keys.url} @ ${rev}`);
      fs.mkdirSync(dir, { recursive: true });
      run("git", ["-C", dir, "init", "-q"]);
      run("git", ["-C", dir, "remote", "add", "origin", w.keys.url]);
      run("git", ["-C", dir, "fetch", "-q", "--depth", w.keys.depth || "1", "origin", rev]);
      run("git", ["-C", dir, "-c", "advice.detachedHead=false", "checkout", "-q", "FETCH_HEAD"]);
    } else if (w.section === "wrap-file") {
      const cache = path.join(sub, "packagecache");
      fs.mkdirSync(cache, { recursive: true });
      const file = path.join(cache, w.keys.source_filename);
      const sha = () => createHash("sha256").update(fs.readFileSync(file)).digest("hex");
      if (!fs.existsSync(file) || sha() !== w.keys.source_hash) {
        for (const url of [w.keys.source_url, w.keys.source_fallback_url].filter(Boolean)) {
          console.log(`  subproject ${name}: fetch ${url}`);
          try { run("curl", ["-fsSL", "--retry", "3", "-o", file, url]); } catch { continue; }
          if (sha() === w.keys.source_hash) break;
          console.log(`  sha256 mismatch from ${url}`);
        }
      }
      if (!fs.existsSync(file) || sha() !== w.keys.source_hash) {
        throw new Error(`subproject ${name}: could not fetch ${w.keys.source_filename} with sha256 ${w.keys.source_hash}`);
      }
      run("tar", ["-xf", file, "-C", sub]);
      if (!fs.existsSync(dir)) throw new Error(`subproject ${name}: ${w.keys.source_filename} did not unpack to ${name}/`);
    } else {
      throw new Error(`subproject ${name}: unsupported wrap kind ${w.section}`);
    }
    if (w.keys.patch_directory) copyTree(path.join(sub, "packagefiles", w.keys.patch_directory), dir);
  }
}

/** Directory holding the emscripten sysroot's libraries (libz.a lives here). */
function sysrootLib() {
  const cache = execFileSync("em-config", ["CACHE"], { encoding: "utf8" }).trim();
  return path.join(cache, "sysroot", "lib", "wasm32-emscripten");
}

function spawnP(cmd, args, cwd) {
  return new Promise((resolve) => {
    const p = spawn(cmd, args, { cwd, stdio: ["ignore", "pipe", "pipe"] });
    let err = "";
    p.stdout.on("data", (d) => { err += d; });
    p.stderr.on("data", (d) => { err += d; });
    p.on("close", (code) => resolve({ code, err }));
  });
}

async function build(rizinDir, buildName = "build-wasm") {
  const B = path.join(rizinDir, buildName);
  fs.rmSync(B, { recursive: true, force: true });
  fs.mkdirSync(B, { recursive: true });

  const emcc = execFileSync("emcc", ["--version"], { encoding: "utf8" }).split("\n")[0];
  if (emcc !== PLAN.emcc) console.warn(`NOTE: plan was frozen with\n  ${PLAN.emcc}\nbuilding with\n  ${emcc}`);

  for (const f of PLAN.configured) {
    fs.mkdirSync(path.dirname(path.join(B, f)), { recursive: true });
    fs.copyFileSync(path.join(HERE, "configured", f), path.join(B, f));
  }
  for (const g of PLAN.generated) {
    const to = path.join(B, g.to);
    fs.mkdirSync(path.dirname(to), { recursive: true });
    if (g.kind === "copy") fs.copyFileSync(path.join(B, g.from), to);
    else if (g.kind === "zip_err_str") {
      fs.writeFileSync(to, zipErrStr(fs.readFileSync(path.join(B, g.zipH), "utf8"), fs.readFileSync(path.join(B, g.zipintH), "utf8")));
    } else throw new Error(`unknown generated kind ${g.kind}`);
  }

  const jobs = Number(process.env.ROMDEV_JOBS) || Math.min(os.availableParallelism(), 16);
  console.log(`==> compile ${PLAN.compile.length} units (${jobs} jobs)`);
  let next = 0, done = 0;
  const failures = [];
  const worker = async () => {
    while (next < PLAN.compile.length && failures.length === 0) {
      const c = PLAN.compile[next++];
      fs.mkdirSync(path.dirname(path.join(B, c.out)), { recursive: true });
      const r = await spawnP("emcc", [...PLAN.flagSets[c.flags], "-o", c.out, "-c", c.src], B);
      if (r.code !== 0) failures.push(`${c.src}\n${r.err}`);
      if (++done % 200 === 0) console.log(`  ${done}/${PLAN.compile.length}`);
    }
  };
  await Promise.all(Array.from({ length: jobs }, worker));
  if (failures.length) throw new Error(`compile failed:\n${failures[0]}`);

  console.log(`==> archive ${PLAN.archives.length} static libs`);
  for (const a of PLAN.archives) {
    const out = path.join(B, a.out);
    fs.rmSync(out, { force: true });
    fs.writeFileSync(`${out}.rsp`, a.members.join(" "));
    run("emar", [a.args, a.out, `@${a.out}.rsp`], { cwd: B });
  }

  console.log("==> link");
  const lib = sysrootLib();
  if (PLAN.link.some((a) => a === "@SYSROOT_LIB@/libz.a") && !fs.existsSync(path.join(lib, "libz.a"))) {
    run("embuilder", ["build", "zlib"]);
  }
  const linkArgs = PLAN.link.map((a) => a.replace("@SYSROOT_LIB@", lib));
  const outIdx = linkArgs.indexOf("-o");
  fs.mkdirSync(path.dirname(path.join(B, linkArgs[outIdx + 1])), { recursive: true });
  run("emcc", linkArgs, { cwd: B });
  console.log(`build.mjs: ${path.join(B, PLAN.target)}`);
}

const [cmd, rizinDir, buildName] = process.argv.slice(2);
const isMain = process.argv[1] && import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href;
if (!isMain) { /* imported (tests) */ }
else if (cmd === "subprojects" && rizinDir) fetchSubprojects(path.resolve(rizinDir));
else if (cmd === "build" && rizinDir) await build(path.resolve(rizinDir), buildName);
else if (cmd) { console.error("usage: build.mjs subprojects <rizin-dir> | build <rizin-dir> [build-dir-name]"); process.exit(2); }
